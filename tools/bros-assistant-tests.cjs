const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/assistant/bros.ts','utf8'), { compilerOptions:{ module:ts.ModuleKind.CommonJS } }).outputText,{exports:exportsObject});
const {normalizeBrosContext,brosCheckoutHint} = exportsObject;
assert.equal(normalizeBrosContext({page:'admin',postalCode:'13507'}),undefined);
const raw={page:'checkout',orderMode:'delivery',postalCode:'13507 <script>',addressComplete:false,nameComplete:false,phoneComplete:false,deliveryAreaKnown:true,minimumMet:true,name:'PRIVATE NAME',phone:'PRIVATE PHONE',street:'PRIVATE ADDRESS',paymentPaid:true};
const ctx=normalizeBrosContext(raw);
assert.equal(ctx.postalCode,'13507');
for(const key of ['name','phone','street','paymentPaid']) assert.equal(key in ctx,false);
assert.match(brosCheckoutHint(ctx),/Hausnummer/);
assert.match(brosCheckoutHint({...ctx,deliveryAreaKnown:false}),/Liefergebiet/);
assert.match(brosCheckoutHint({...ctx,addressComplete:true,minimumMet:false}),/Mindestbestellwert/);
assert.match(brosCheckoutHint({...ctx,orderMode:'pickup'}),/Telefonnummer/);
assert.match(brosCheckoutHint({...ctx,addressComplete:true,nameComplete:true,phoneComplete:true,plannedRequired:true,plannedComplete:false}),/Uhrzeit/);
assert.match(brosCheckoutHint({...ctx,addressComplete:true,nameComplete:true,phoneComplete:true}),/erst nach der Bestätigung/);
assert.equal(normalizeBrosContext({...raw,addressComplete:'true'}).addressComplete,false);
console.log('Bros: PASS (context allowlist, no full address/contact/payment data, bounded postcode, correct contextual guidance)');
