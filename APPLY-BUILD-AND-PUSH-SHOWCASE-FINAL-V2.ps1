function Write-Step([string]$Text) {
    Write-Host ""
    Write-Host "==> $Text" -ForegroundColor Cyan
}

function Get-ProjectPath([string]$Root, [string]$Relative) {
    $normalized = $Relative.Replace('/', [IO.Path]::DirectorySeparatorChar)
    $rootFull = [IO.Path]::GetFullPath($Root).TrimEnd('\')
    $full = [IO.Path]::GetFullPath((Join-Path $rootFull $normalized))
    if (-not $full.StartsWith($rootFull + '\', [StringComparison]::OrdinalIgnoreCase)) {
        throw "Proje disi yol reddedildi: $Relative"
    }
    return $full
}

function Get-Sha256([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return "" }
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

function Assert-SafeManifest {
    foreach ($relative in $Manifest) {
        $lower = ('/' + $relative.Replace('\', '/').ToLowerInvariant() + '/')
        if ($lower -match '/(\.git|\.next|node_modules|dashboard|coverage|dist|build|logs?|backups?)/') {
            throw "Yasakli klasor manifestte bulundu: $relative"
        }
        $name = [IO.Path]::GetFileName($relative).ToLowerInvariant()
        if ($name -match '^\.env($|\.)' -or $name -match '\.(pem|key|p12|pfx|crt|cer|der|sqlite|sqlite3|db|log|mp4|mov|mkv|avi|webm|m4v|mp3|wav|flac)$') {
            throw "Yasakli dosya manifestte bulundu: $relative"
        }
    }
}

function Invoke-Checked(
    [string]$Executable,
    [string[]]$Arguments,
    [string]$WorkingDirectory,
    [string]$Label
) {
    Write-Host "  $Label" -ForegroundColor DarkGray
    Push-Location $WorkingDirectory
    try {
        & $Executable @Arguments
        $exitCode = $LASTEXITCODE
    } finally {
        Pop-Location
    }
    if ($exitCode -ne 0) {
        throw "$Label basarisiz oldu. Cikis kodu: $exitCode"
    }
}

function Copy-ExactFile([string]$Source, [string]$Destination) {
    $parent = Split-Path -Parent $Destination
    if (-not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Path $parent -Force | Out-Null
    }
    Copy-Item -LiteralPath $Source -Destination $Destination -Force
}

function Restore-ProjectFiles([string]$BackupRoot, [string[]]$MissingBefore) {
