            $to = Get-ProjectPath $GitHubRoot $relative
            $backup = Get-ProjectPath $githubBackupRoot $relative
            if (Test-Path -LiteralPath $backup -PathType Leaf) {
                Copy-ExactFile $backup $to
            } elseif ($githubMissing.Contains($relative)) {
                Remove-Item -LiteralPath $to -Force -ErrorAction SilentlyContinue
            }
        }
    }
    throw $gitFailure
} finally {
    Remove-Item -LiteralPath $githubBackupRoot -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $tempRoot -Recurse -Force -ErrorAction SilentlyContinue
}

