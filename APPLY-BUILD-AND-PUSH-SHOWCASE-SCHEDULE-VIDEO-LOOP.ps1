$GitHubRoot = [IO.Path]::GetFullPath($GitHubRoot).TrimEnd("\")

if (-not (Test-Path -LiteralPath $ProjectRoot -PathType Container)) {
    throw "Kaynak proje bulunamadi: $ProjectRoot"
}
if (-not (Test-Path -LiteralPath (Join-Path $ProjectRoot "package.json") -PathType Leaf)) {
    throw "Kaynak projede package.json bulunamadi."
}
if (-not (Test-Path -LiteralPath (Join-Path $GitHubRoot ".git") -PathType Container)) {
    throw "GitHub repo klasoru bulunamadi: $GitHubRoot"
}

$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$workRoot = Join-Path $env:TEMP "burger-showcase-schedule-video-loop-$stamp"
$payloadZip = Join-Path $workRoot "payload.zip"
$payloadRoot = Join-Path $workRoot "payload"
$backupRoot = Join-Path $workRoot "project-backup"
$existingBefore = @{}
$buildSucceeded = $false

[IO.Directory]::CreateDirectory($payloadRoot) | Out-Null
[IO.Directory]::CreateDirectory($backupRoot) | Out-Null

function Restore-ProjectFiles {
    foreach ($relative in $Manifest) {
        $target = Resolve-ProjectFile $ProjectRoot $relative
        $backup = Resolve-ProjectFile $backupRoot $relative
        $existed = [bool]$existingBefore[$relative]

        if ($existed -and (Test-Path -LiteralPath $backup -PathType Leaf)) {
            Ensure-Parent $target
            Copy-Item -LiteralPath $backup -Destination $target -Force
        } elseif (-not $existed -and (Test-Path -LiteralPath $target -PathType Leaf)) {
            Remove-Item -LiteralPath $target -Force
        }
    }
}

try {
    Write-Step "Teslimat payload'i aciliyor ve SHA-256 ile dogrulaniyor"
    $payloadBytes = [Convert]::FromBase64String(($PayloadBase64 -replace "\s", ""))
    [IO.File]::WriteAllBytes($payloadZip, $payloadBytes)
    Expand-Archive -LiteralPath $payloadZip -DestinationPath $payloadRoot -Force

    foreach ($relative in $Manifest) {
        $payloadFile = Resolve-ProjectFile $payloadRoot $relative
        if (-not (Test-Path -LiteralPath $payloadFile -PathType Leaf)) {
            throw "Payload dosyasi eksik: $relative"
        }
        if ((Get-Sha256 $payloadFile) -ne $ExpectedOutputHashes[$relative]) {
            throw "Payload SHA-256 dogrulamasi basarisiz: $relative"
        }
    }

    Write-Step "Guncel kaynak dosyalar kontrol ediliyor"
    foreach ($relative in $Manifest) {
        $current = Resolve-ProjectFile $ProjectRoot $relative
        $expectedSource = $ExpectedSourceHashes[$relative]
        $expectedOutput = $ExpectedOutputHashes[$relative]
        $exists = Test-Path -LiteralPath $current -PathType Leaf
        $existingBefore[$relative] = $exists

        if ($exists) {
            $actual = Get-Sha256 $current
            $alreadyApplied = $actual -eq $expectedOutput
            $matchesCollectedSource = $expectedSource -and $actual -eq $expectedSource

            if (-not $alreadyApplied -and -not $matchesCollectedSource) {
                throw "Dosya kaynak ZIP alindiktan sonra degismis: $relative`nGuvenlik icin uzerine yazilmadi."
            }

            $backup = Resolve-ProjectFile $backupRoot $relative
            Ensure-Parent $backup
            Copy-Item -LiteralPath $current -Destination $backup -Force
        } elseif ($expectedSource) {
            throw "Beklenen mevcut dosya bulunamadi: $relative"
        }
    }

    Write-Step "Haftalik program ve video loop dosyalari uygulaniyor"
    foreach ($relative in $Manifest) {
        $source = Resolve-ProjectFile $payloadRoot $relative
        $target = Resolve-ProjectFile $ProjectRoot $relative
        Ensure-Parent $target
        Copy-Item -LiteralPath $source -Destination $target -Force

        if ((Get-Sha256 $target) -ne $ExpectedOutputHashes[$relative]) {
            throw "Uygulama sonrasi SHA-256 dogrulamasi basarisiz: $relative"
        }
        Write-Host "  uygulandi: $relative" -ForegroundColor DarkGray
    }

    Push-Location $ProjectRoot
    try {
        Write-Step "Yeni ozellik regresyon testi"
        & node "tools\showcase-schedule-video-loop-tests.cjs"
        if ($LASTEXITCODE -ne 0) {
            throw "Haftalik program / video loop testi basarisiz."
        }

        Write-Step "Tum Showcase regresyon testleri"
        & npm.cmd run showcase:test
        if ($LASTEXITCODE -ne 0) {
            throw "Showcase regresyon testleri basarisiz."
        }

        Write-Step "TypeScript typecheck"
        & npm.cmd run typecheck
        if ($LASTEXITCODE -ne 0) {
            throw "TypeScript typecheck basarisiz."
        }

        Write-Step "Temiz production build"
        $nextPath = Join-Path $ProjectRoot ".next"
        if (Test-Path -LiteralPath $nextPath) {
            Remove-Item -LiteralPath $nextPath -Recurse -Force
        }

        & npm.cmd run build
        if ($LASTEXITCODE -ne 0) {
            throw "Production build basarisiz."
        }

        $buildSucceeded = $true
    }
    finally {
        Pop-Location
    }
}
catch {
    Write-Host ""
    Write-Host "UYGULAMA / BUILD HATASI: $($_.Exception.Message)" -ForegroundColor Red
    if (-not $buildSucceeded) {
        Write-Host "Kaynak proje dosyalari otomatik geri yukleniyor..." -ForegroundColor Yellow
        Restore-ProjectFiles
    }
    throw
}

try {
    Write-Step "GitHub main branch kontrolu"
    Push-Location $GitHubRoot
    try {
        & git.exe checkout main
        if ($LASTEXITCODE -ne 0) {
            throw "main branch acilamadi."
        }
    }
    finally {
        Pop-Location
    }

    Write-Step "Yalniz bu teslimatin dosyalari GitHub klasorune aktariliyor"
    foreach ($relative in $Manifest) {
        $source = Resolve-ProjectFile $ProjectRoot $relative
        $target = Resolve-ProjectFile $GitHubRoot $relative
        Ensure-Parent $target
        Copy-Item -LiteralPath $source -Destination $target -Force
        Write-Host "  senkronlandi: $relative" -ForegroundColor DarkGray
    }

    Push-Location $GitHubRoot
    try {
        foreach ($relative in $Manifest) {
            & git.exe add -- $relative
            if ($LASTEXITCODE -ne 0) {
                throw "git add basarisiz: $relative"
            }
        }

        & git.exe diff --cached --quiet
        $diffExit = $LASTEXITCODE

        if ($diffExit -eq 1) {
            & git.exe commit -m "feat(showcase): add weekly schedule and scene-timed video playback"
            if ($LASTEXITCODE -ne 0) {
                throw "git commit basarisiz."
            }
        } elseif ($diffExit -ne 0) {
            throw "git diff kontrolu basarisiz."
        } else {
            Write-Host "  GitHub klasorunde yeni commit gerektiren fark yok." -ForegroundColor DarkYellow
        }

        & git.exe push origin main
        if ($LASTEXITCODE -ne 0) {
            throw "git push basarisiz."
        }
    }
    finally {
        Pop-Location
    }

    Write-Host ""
    Write-Host "TAMAMLANDI KANKAM :)" -ForegroundColor Green
    Write-Host "- Haftalik gun/saat programi aktif." -ForegroundColor Green
    Write-Host "- Hafta ici 10:00-16:00 Mittagsmenu hazir ayari aktif." -ForegroundColor Green
    Write-Host "- Video dosyasi bitince sahne erken atlamiyor." -ForegroundColor Green
    Write-Host "- Video sahne suresi boyunca tekrar ediyor veya son karede bekliyor." -ForegroundColor Green
    Write-Host "- Build ve GitHub push basarili." -ForegroundColor Green
    Write-Host "Vercel deploy bittikten sonra admin ve Showcase sayfasinda Ctrl+F5 yap." -ForegroundColor Yellow
}
catch {
    Write-Host ""
    Write-Host "GITHUB HATASI: $($_.Exception.Message)" -ForegroundColor Red
    Write-Host "Yerel C:\Web\burger projesi test ve build'den gecti; geri alinmadi." -ForegroundColor Yellow
    Write-Host "Yalniz GitHub senkronu/push islemini kontrol etmen gerekiyor." -ForegroundColor Yellow
    throw
}
finally {
    if (Test-Path -LiteralPath $workRoot) {
        Remove-Item -LiteralPath $workRoot -Recurse -Force -ErrorAction SilentlyContinue
    }
}
